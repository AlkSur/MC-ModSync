_pinned_ctx: Optional[ssl.SSLContext] = None
_pinned_ok = False        # 粘性：内置库成功过一次后，后续请求直接走内置库
_pinned_tried = False     # 本次运行是否触发过内置库重试


def pinned_context() -> ssl.SSLContext:
    """返回仅含内置根证书的校验上下文（惰性构建、进程内缓存）。

    注意不能用 create_default_context——它会顺带 load_default_certs() 把本机
    证书库全部加载进来，等于没绕开污染源；这里手工构建、只信任内置根。
    """
    global _pinned_ctx
    if _pinned_ctx is None:
        ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)   # 默认开启校验，不加载本机库
        ctx.load_verify_locations(cadata=_PEMS)
        _pinned_ctx = ctx
    return _pinned_ctx


def is_cert_verify_error(e: BaseException) -> bool:
    """判断异常是否属于"证书校验失败"类（只这类才值得用内置根重试）。"""
    seen, stack = set(), [e]
    while stack:
        cur = stack.pop()
        if id(cur) in seen:
            continue
        seen.add(id(cur))
        if isinstance(cur, ssl.SSLCertVerificationError):
            return True
        text = " ".join([type(cur).__name__, str(cur)]).upper()
        if "CERTIFICATE_VERIFY_FAILED" in text:
            return True
        stack.extend(x for x in (getattr(cur, "reason", None), getattr(cur, "__cause__", None),
                                 getattr(cur, "__context__", None)) if isinstance(x, BaseException))
    return False


def pinned_mode() -> bool:
    """当前是否已进入粘性内置库模式。"""
    return _pinned_ok


def pinned_tried() -> bool:
    """本次运行是否触发过内置库重试（诊断用）。"""
    return _pinned_tried


_pinned_handler: Optional[urllib.request.HTTPSHandler] = None


def pinned_https_handler() -> urllib.request.HTTPSHandler:
    """内置根证书的 HTTPSHandler（惰性构建、进程内缓存）。"""
    global _pinned_handler
    if _pinned_handler is None:
        _pinned_handler = urllib.request.HTTPSHandler(context=pinned_context())
    return _pinned_handler


def note_pinned_ok() -> None:
    """内置库重试成功后标记粘性模式（后续请求直接走内置库）。"""
    global _pinned_ok
    _pinned_ok = True


def open_https(req: urllib.request.Request, timeout: int,
               log: Optional[Callable[[str], None]] = None):
    """urllib.request.urlopen 的替代入口：默认库失败(证书类)时用内置根重试。

    其余错误类型（超时/连接拒绝/HTTP错误）不重试，行为与 urlopen 一致。
    """
    global _pinned_ok, _pinned_tried
    if _pinned_ok:
        return urllib.request.urlopen(req, timeout=timeout, context=pinned_context())
    try:
        return urllib.request.urlopen(req, timeout=timeout)
    except urllib.error.URLError as e:
        if not is_cert_verify_error(e):
            raise
        _pinned_tried = True
        try:
            resp = urllib.request.urlopen(req, timeout=timeout, context=pinned_context())
        except Exception:                       # noqa: BLE001  内置库也失败：抛原始错误
            raise e                             # noqa: B904  诊断信息基于原始错误
        _pinned_ok = True
        if log:
            log("提示: 本机证书库校验失败，已自动改用更新器内置可信根证书（不影响安全性）")
        return resp
